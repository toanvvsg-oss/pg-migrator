#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  -- Least-privilege target migration role using PG 16 pg_create_subscription (NOSUPERUSER)
  CREATE ROLE migrator WITH LOGIN PASSWORD '${TARGET_MIGRATOR_PASSWORD}' REPLICATION NOSUPERUSER NOCREATEROLE;
  CREATE ROLE appuser WITH LOGIN PASSWORD '${APP_DB_PASSWORD}' NOSUPERUSER NOCREATEROLE NOCREATEDB;

  GRANT pg_create_subscription TO migrator;
  GRANT pg_monitor TO migrator;
  ALTER DATABASE ${POSTGRES_DB} OWNER TO migrator;
  ALTER SCHEMA public OWNER TO migrator;

  GRANT CONNECT, TEMP ON DATABASE ${POSTGRES_DB} TO appuser;
  GRANT USAGE ON SCHEMA public TO appuser;
  ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA public
      GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO appuser;
  ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA public
      GRANT USAGE, SELECT ON SEQUENCES TO appuser;
EOSQL
